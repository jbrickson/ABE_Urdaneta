create table public.guests (
  usn text primary key check (usn ~ '^[A-Z0-9-]+$'),
  name text not null check (length(trim(name)) > 0),
  status text not null default 'Pending'
    check (status in ('Pending', 'Attending', 'Not Attending')),
  confirmed_at timestamptz,
  created_at timestamptz not null default now(),
  constraint guest_confirmation_matches_status check (
    (status = 'Pending' and confirmed_at is null)
    or (status <> 'Pending' and confirmed_at is not null)
  )
);

alter table public.guests enable row level security;
revoke all on table public.guests from anon, authenticated;
grant all on table public.guests to service_role;

